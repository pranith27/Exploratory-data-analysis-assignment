@dataclass
class ExecutionResult:
    success: bool
    stdout: str = ""
    error: str = ""
    result: dict = field(default_factory=dict)
    figure_paths: list = field(default_factory=list)
    context_out: dict = field(default_factory=dict)


class CodeExecutor:
    """Executes agent-generated code in a controlled namespace.

    Only code generated by the agents in this module is executed (never raw
    user input). The namespace exposes pandas/numpy/matplotlib/seaborn/
    scikit-learn helpers plus the working DataFrame as ``df`` and an output
    dict ``result`` that generated code must populate. The real library
    (v0.0.0.9017) uses sandboxed execution; this local reproduction uses a
    plain namespace because all generated code is produced by deterministic
    templates in this file -- see report.md "Trust & guardrails".
    """

    def __init__(self, figures_dir: Path):
        self.figures_dir = Path(figures_dir)
        self.figures_dir.mkdir(parents=True, exist_ok=True)

    def run(self, code: str, df: pd.DataFrame, extra: dict | None = None) -> ExecutionResult:
        import seaborn as sns  # local import: keeps module import light
        from sklearn.cluster import KMeans
        from sklearn.ensemble import IsolationForest, RandomForestRegressor
        from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
        from sklearn.model_selection import train_test_split
        from sklearn.preprocessing import StandardScaler

        ns: dict = {
            "pd": pd,
            "np": np,
            "plt": plt,
            "sns": sns,
            "KMeans": KMeans,
            "IsolationForest": IsolationForest,
            "RandomForestRegressor": RandomForestRegressor,
            "mean_absolute_error": mean_absolute_error,
            "mean_squared_error": mean_squared_error,
            "r2_score": r2_score,
            "train_test_split": train_test_split,
            "StandardScaler": StandardScaler,
            "math": math,
            "RANDOM_STATE": RANDOM_STATE,
            "df": df,
            "FIGDIR": str(self.figures_dir),
            "result": {},
            "context": dict(extra or {}),
        }
        buf = io.StringIO()
        before = set(self.figures_dir.glob("*.png"))
        try:
            with redirect_stdout(buf):
                exec(compile(code, "<agent-code>", "exec"), ns)
            figs = sorted(str(p) for p in set(self.figures_dir.glob("*.png")) - before)
            return ExecutionResult(
                success=True,
                stdout=buf.getvalue(),
                result=dict(ns.get("result") or {}),
                figure_paths=figs,
                context_out=dict(ns.get("context") or {}),
            )
        except Exception:
            return ExecutionResult(success=False, stdout=buf.getvalue(),
                                   error=traceback.format_exc(limit=3))


